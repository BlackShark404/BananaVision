import joblib
import numpy as np
import math
import os
import sys

# The business clock is Asia/Manila (backend/app/core/time.py), whatever zone this machine uses.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "backend"))
from app.core.time import now_manila  # noqa: E402

MODEL_PATH = "backend/app/ml/weights/spoilage_rfr.joblib"

def calc_vpd(t_c, rh):
    rh = max(min(rh, 100), 0)
    svp = 0.61078 * math.exp((17.27 * t_c) / (t_c + 237.3))
    avp = (rh / 100.0) * svp
    return round(svp - avp, 4)

def run_matrix_test():
    output_lines = []
    
    def log(msg):
        print(msg)
        output_lines.append(msg)

    log(f"Loading RFR model from {MODEL_PATH}...")
    if not os.path.exists(MODEL_PATH):
        log(f"Error: Model not found at {MODEL_PATH}")
        return

    loaded_data = joblib.load(MODEL_PATH)
    rfr_model = loaded_data.get('model') if isinstance(loaded_data, dict) and 'model' in loaded_data else loaded_data
    
    # Auto-detect if enhanced model (6 features) or legacy (4 features)
    n_features = rfr_model.n_features_in_ if hasattr(rfr_model, 'n_features_in_') else 4
    log(f"Model expects {n_features} features")

    conditions = [
        {"label": "Cool/Humid", "temp": 26.5, "hum": 92.0},
        {"label": "Typical PH", "temp": 31.0, "hum": 77.0},
        {"label": "Hot/Dry", "temp": 33.0, "hum": 72.0},
    ]
    
    cultivars = {0: 'Lakatan', 1: 'Latundan', 2: 'Cardaba'}
    ripeness = {0: 'Unripe', 1: 'Semi-Ripe', 2: 'Ripe', 3: 'Overripe'}
    treatments = {0: 'Natural', 1: 'Ethephon'}

    results = []
    
    log("\n" + "="*95)
    log(f"{'Cultivar':10s} | {'Ripeness':10s} | {'Treatment':10s} | {'Condition':12s} | {'Temp / RH':12s} => {'Shelf Life'}")
    log("-" * 95)

    for c in [0, 1, 2]:
        for r in [0, 1, 2, 3]:
            for t in [0, 1]:
                for cond in conditions:
                    vpd = calc_vpd(cond["temp"], cond["hum"])
                    
                    if n_features >= 14:
                        # Full feature set as generated by export_timeline.py
                        features = np.array([[c, r, cond["temp"], cond["hum"], t, vpd, 0.0, 0.0, 12.0, 3.0, 1.0, 24.0, cond["temp"], cond["hum"]]])
                    elif n_features >= 6:
                        features = np.array([[c, r, cond["temp"], cond["hum"], vpd, t]])
                    else:
                        features = np.array([[c, r, cond["temp"], cond["hum"]]])
                    
                    try:
                        prediction = rfr_model.predict(features)
                        days_float = float(prediction[0])
                        
                        # Match BananaVision's empirical tree quantiles logic
                        if hasattr(rfr_model, 'estimators_'):
                            tree_preds = np.array([tree.predict(features)[0] for tree in rfr_model.estimators_])
                            low = max(0, round(np.percentile(tree_preds, 10)))
                            high = round(np.percentile(tree_preds, 90))
                        else:
                            pred_int = max(0, round(days_float))
                            margin = max(1, round(days_float * 0.15))
                            low = max(0, pred_int - margin)
                            high = pred_int + margin
                            
                        if low == high:
                            days = f"{low} days"
                        else:
                            days = f"{low}-{high} days"
                            
                    except Exception as e:
                        days = f"Error: {e}"
                        
                    results.append({
                        "cultivar": c,
                        "ripeness": r,
                        "treatment": t,
                        "condition": cond["label"],
                        "predicted_days": days
                    })
                    
                    env_str = f"{cond['temp']}°C / {cond['hum']}%"
                    log(f"{cultivars[c]:10s} | {ripeness[r]:10s} | {treatments[t]:10s} | {cond['label']:12s} | {env_str:12s} => {days}")
            
            log("-" * 95)  # Separator for each Ripeness stage

    log("="*95)
    log(f"Total Tests: {len(results)}")

    # Save to text file
    timestamp = now_manila().strftime("%Y%m%d_%H%M%S")
    out_file = f"matrix_results_{timestamp}.txt"
    with open(out_file, "w") as f:
        f.write("\n".join(output_lines))
        
    print(f"\n✅ Detailed matrix test saved to {out_file}")

if __name__ == "__main__":
    run_matrix_test()
